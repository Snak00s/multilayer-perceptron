import numpy as np
import sys
import pandas as pd
from training.model import model
from utils.parser import Parser

def createExpectedOutput(rawOutput: list):
	ret = []
	for x in rawOutput:
		if (x == 'M'):
			ret.append([1, 0])
		elif (x == 'B'):
			ret.append([0, 1])
		else:
			raise AssertionError(f"Invalid output : {x}, should be 'B' or 'M'")
	return ret

def help():
	print("model mlp tester, this function will use the model trained by 'training.model.py' and use it on the given datalist generated by 'data_repartition'.")
	print("\t--data: 'file.csv' set the list of data to use for testing.")
	print("\t--model: set the model to use for testing.")
	return

def main():
	try:
		parser = Parser()


		parser.special_help(help)
		parser.add_arg("data", ammount=1, argType=str)
		parser.add_arg("model", ammount=1, argType=str)

		args = parser.parse_args()

		data = pd.read_csv(args['data'][0], header=None)

		testData = data.iloc[:, 1:-1].sample(frac=1)

		testInputs = np.array(testData.iloc[:100, 1:])
		testInputs = (testInputs - testInputs.mean(axis=0)) / testInputs.std(axis=0)
		testOutputs = np.array(createExpectedOutput(np.array(testData.iloc[:100, :1])))

		mlp = np.load(args["model"][0], allow_pickle=True)
		mlp : model = mlp.item()

		res = mlp.useModel((testInputs, testOutputs))

		print(f"cost: {res[0]:.4f}, accuracy: {res[1]*100:.3f}%")

	except Exception as AE:
		print(f"{type(AE).__name__}: {AE}", file=sys.stderr)
		exit(1)

	except KeyboardInterrupt:
		print("\nKeyboard Interuption", file=sys.stderr)

		return

if __name__ == "__main__":
	main()