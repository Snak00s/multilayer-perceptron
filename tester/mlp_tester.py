import numpy as np
from training.model import model
import sys
from utils.parser import Parser

def help():
	print("model mlp tester, this function will use the model trained by 'training.model.py' and use it on the given datalist generated by 'data_repartition'.")
	print("\t--data: set the list of data to use for testing.")
	print("\t--model: set the model to use for testing.")
	return

def main():
	try:
		parser = Parser()

		parser.special_help(help)
		parser.add_arg("model", ammount=1, argType=str)
		parser.add_arg("data", ammount=1, argType=str)

		args = parser.parse_args()

		data = np.load(args["data"][0], allow_pickle=True)

		testData = data.item()['test']

		mlp = np.load(args["model"][0], allow_pickle=True)

		mlp : model = mlp.item()

		res = mlp.useModel(testData)

		print(f"cost: {res[0]:.4f}, accuracy: {res[1]*100:.3f}%")

	except Exception as AE:
		print(f"{type(AE).__name__}: {AE}", file=sys.stderr)
		exit(1)

	except KeyboardInterrupt:
		print("\nKeyboard Interuption", file=sys.stderr)

		return

if __name__ == "__main__":
	main()